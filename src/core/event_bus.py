# Generic Event TypeVar for strong subscriber typing
E = TypeVar("E", bound=BaseEvent)
EventHandler = Union[Callable[[E], Awaitable[None]], Callable[[E], None]]


# ------------------------------------------------------------------------------
# 2. Async Event Bus Implementation
# ------------------------------------------------------------------------------

class EventBus:
    """
    Lightweight, asynchronous Pub/Sub Event Bus.
    Features:
    - Strongly-typed topic subscriptions by Event Class or event_type string.
    - Background queue worker for non-blocking asynchronous event decoupling.
    - Isolated error boundaries: a crashing handler never crashes the event loop or other subscribers.
    - Full telemetry tracking: published, delivered, and error counts.
    """

    def __init__(self, max_queue_size: int = 10000) -> None:
        self._subscribers: Dict[str, List[Callable[[Any], Any]]] = {}
        self._queue: asyncio.Queue[Optional[BaseEvent]] = asyncio.Queue(maxsize=max_queue_size)
        self._worker_task: Optional[asyncio.Task[None]] = None
        self._is_running: bool = False

        # Telemetry metrics
        self.events_published: int = 0
        self.events_delivered: int = 0
        self.errors_caught: int = 0

    def subscribe(
        self,
        event_cls: Union[Type[E], str],
        handler: Callable[[Any], Any],
    ) -> None:
        """
        Subscribes a synchronous or asynchronous callback to a specific event type.
        """
        event_type = event_cls if isinstance(event_cls, str) else event_cls.__name__
        if event_type not in self._subscribers:
            self._subscribers[event_type] = []
        if handler not in self._subscribers[event_type]:
            self._subscribers[event_type].append(handler)
            logger.debug("Subscribed %s to %s", getattr(handler, "__name__", str(handler)), event_type)

    def unsubscribe(
        self,
        event_cls: Union[Type[E], str],
        handler: Callable[[Any], Any],
    ) -> None:
        """
        Unsubscribes a callback from an event type.
        """
        event_type = event_cls if isinstance(event_cls, str) else event_cls.__name__
        if event_type in self._subscribers and handler in self._subscribers[event_type]:
            self._subscribers[event_type].remove(handler)
            logger.debug("Unsubscribed %s from %s", getattr(handler, "__name__", str(handler)), event_type)

    def on(self, event_cls: Union[Type[E], str]) -> Callable[[Callable[[Any], Any]], Callable[[Any], Any]]:
        """
        Decorator pattern for registering event subscribers:
        @event_bus.on(MarketTickEvent)
        async def on_tick(event: MarketTickEvent):
            ...
        """
        def decorator(handler: Callable[[Any], Any]) -> Callable[[Any], Any]:
            self.subscribe(event_cls, handler)
            return handler
        return decorator

    async def publish(self, event: BaseEvent) -> None:
        """
        Enqueues an event for asynchronous processing by the worker loop.
        Non-blocking to the caller.
        """
        self.events_published += 1
        await self._queue.put(event)

    async def dispatch(self, event: BaseEvent) -> None:
        """
        Synchronously (inline) dispatches an event to all subscribed handlers with error isolation.
        Useful for deterministic testing or immediate event execution.
        """
        event_type = event.event_type
        handlers = self._subscribers.get(event_type, []).copy()

        # Also dispatch to wildcard listeners if registered
        wildcard_handlers = self._subscribers.get("*", []).copy()
        all_handlers = handlers + wildcard_handlers

        for handler in all_handlers:
            try:
                if asyncio.iscoroutinefunction(handler):
                    await handler(event)
                else:
                    handler(event)
                self.events_delivered += 1
            except Exception as exc:
                self.errors_caught += 1
                handler_name = getattr(handler, "__name__", str(handler))
                logger.error(
                    "Error in event handler '%s' processing '%s': %s",
                    handler_name,
                    event_type,
                    exc,
                    exc_info=True,
                )

    async def start(self) -> None:
        """Starts the background worker queue consumer task."""
        if self._is_running:
            return
        self._is_running = True
        self._worker_task = asyncio.create_task(self._process_queue())
        logger.info("EventBus background worker started.")

    async def stop(self) -> None:
        """Gracefully drains the queue and stops the worker task."""
        if not self._is_running:
            return
        self._is_running = False
        await self._queue.put(None)  # Sentinel to terminate worker
        if self._worker_task:
            await self._worker_task
            self._worker_task = None
        logger.info("EventBus background worker stopped.")

    async def wait_until_idle(self) -> None:
        """Waits until all pending events in the queue have been fully processed."""
        await self._queue.join()

    async def _process_queue(self) -> None:
        """Internal worker loop consuming events from the queue."""
        while True:
            event = await self._queue.get()
            if event is None:
                self._queue.task_done()
                break
            try:
                await self.dispatch(event)
            finally:
                self._queue.task_done()

    def clear(self) -> None:
        """Clears all subscribers and resets telemetry metrics."""
        self._subscribers.clear()
        self.events_published = 0
        self.events_delivered = 0
        self.errors_caught = 0


# Global singleton event bus instance
event_bus: EventBus = EventBus()
