"""
src/core/event_bus.py
Lightweight, zero-framework asynchronous event bus with strongly-typed Pydantic v2
event schemas and isolated error boundaries.
"""

import asyncio
import logging
import uuid
from datetime import datetime, timezone
from typing import (
    Any,
    Awaitable,
    Callable,
    Dict,
    List,
    Optional,
    Type,
    TypeVar,
    Union,
)
from pydantic import BaseModel, Field

logger = logging.getLogger("event_bus")


# ------------------------------------------------------------------------------
# 1. Typed Event Schemas (Pydantic v2)
# ------------------------------------------------------------------------------

class BaseEvent(BaseModel):
    """Base event model with automatic UUID, UTC timestamp, and typed event discriminator."""

    event_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Globally unique identifier for the event",
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp when the event was generated",
    )
    event_type: str = Field(
        description="String discriminator identifier for event routing",
    )

    model_config = {"arbitrary_types_allowed": True}


class MarketTickEvent(BaseEvent):
    """Real-time market quote tick for an underlying instrument or options contract."""

    event_type: str = "MarketTickEvent"
    symbol: str = Field(description="Ticker or OCC option contract identifier")
    bid: float = Field(ge=0.0, description="Best bid price")
    ask: float = Field(ge=0.0, description="Best ask price")
    last_price: float = Field(ge=0.0, description="Last traded price")
    volume: int = Field(default=0, ge=0, description="Cumulative or tick volume")

    @property
    def mid_price(self) -> float:
        """Calculates arithmetic midpoint of the bid-ask spread."""
        return (self.bid + self.ask) / 2.0

    @property
    def spread(self) -> float:
        """Calculates absolute bid-ask spread."""
        return self.ask - self.bid

    @property
    def slippage_pct(self) -> float:
        """Calculates bid-ask spread as a fraction of midpoint."""
        mid = self.mid_price
        return (self.spread / mid) if mid > 0 else 0.0


class OptionsChainSnapshotEvent(BaseEvent):
    """Aggregated snapshot of an option chain for volatility and strike analysis."""

    event_type: str = "OptionsChainSnapshotEvent"
    symbol: str = Field(description="Underlying root symbol (e.g. SPY, QQQ)")
    underlying_price: float = Field(gt=0.0, description="Current price of the underlying asset")
    expiration_dates: List[str] = Field(description="List of available expiration dates (YYYY-MM-DD)")
    strikes: List[float] = Field(description="Sorted list of available strike prices")
    contracts_count: int = Field(ge=0, description="Total contracts discovered in the chain")
    snapshot_data: Dict[str, Any] = Field(
        default_factory=dict,
        description="Detailed contract dictionaries mapping OCC symbol to quote snapshots",
    )


class SignalEvent(BaseEvent):
    """Quantitative signal generated by the regime detector or technical indicators."""

    event_type: str = "SignalEvent"
    symbol: str = Field(description="Underlying ticker symbol")
    regime: str = Field(description="Classified market regime (e.g. HIGH_IV_RANGEBOUND, HIGH_IV_TRENDING)")
    signal_type: str = Field(description="Suggested structure: BULL_PUT, BEAR_CALL, IRON_CONDOR, DEBIT_SPREAD")
    confidence: float = Field(ge=0.0, le=1.0, description="Signal confidence score between 0.0 and 1.0")
    metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description="Supporting metrics: IVR, IVP, ADX, trend slope, historical volatility",
    )


